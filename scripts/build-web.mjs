// Copies the share page's static files (worker/web) into the Worker's assets dir and writes
// worker/src/generated-web.ts with a content hash used to cache-bust player.js and recitbot.css.
// Served by Workers Static Assets at /s/* (plus /favicon.ico and /apple-touch-icon.png at the root).
import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "worker", "web");
const pub = join(root, "worker", "public");
const out = join(pub, "s");

const files = (dir) =>
  readdirSync(dir)
    .sort()
    .flatMap((n) => (statSync(join(dir, n)).isDirectory() ? files(join(dir, n)) : [join(dir, n)]));

rmSync(out, { recursive: true, force: true });
const hash = createHash("sha256");
let bytes = 0;
for (const f of files(src)) {
  const rel = relative(src, f).replaceAll("\\", "/");
  const buf = readFileSync(f);
  hash.update(rel).update(buf);
  bytes += buf.length;
  mkdirSync(dirname(join(out, rel)), { recursive: true });
  copyFileSync(f, join(out, rel));
}
copyFileSync(join(src, "favicon.ico"), join(pub, "favicon.ico"));

// /s/plain/*: the same style and scripts for a deployment without BRAND_NAME (worker/src/share.ts webFile), with the product
// name taken out. Made from the hashed files above, so the same ?v= fits. Anything left over stops the build.
const PLAIN = {
  "recitbot.css": ["watch.css", [["Recitbot share page", "Share page"], ['"Powered by Recitbot"', '"Powered by"'], ["url(fonts/", "url(../fonts/"]]],
  "player.js": ["player.js", [["Recitbot share page player", "Share page player"]]],
  "comments.js": ["comments.js", [["Recitbot watch page", "Watch page"], ["recitbot.commentName", "viewer.commentName"]]],
  "meta.js": ["meta.js", [["Recitbot watch page", "Watch page"], ['`${data.title || "Recitbot recording"} · Recitbot`', 'data.title || "Screen recording"']]],
};
mkdirSync(join(out, "plain"), { recursive: true });
for (const [file, [to, swaps]] of Object.entries(PLAIN)) {
  let text = readFileSync(join(src, file), "utf8");
  for (const [from, by] of swaps) {
    if (!text.includes(from)) throw new Error(`build-web: ${file} no longer contains ${from}`);
    text = text.replaceAll(from, by);
  }
  if (/recitbot/i.test(text)) throw new Error(`build-web: ${file} still names the product in its plain copy`);
  writeFileSync(join(out, "plain", to), text);
}

copyFileSync(join(src, "apple-touch-icon.png"), join(pub, "apple-touch-icon.png"));

// Workers Static Assets header rules. Page refs to CSS/JS carry ?v=<hash>; fonts and images keep stable names.
writeFileSync(
  join(pub, "_headers"),
  [
    "/s/*",
    "  Cache-Control: public, max-age=604800",
    "  X-Content-Type-Options: nosniff",
    "  X-Robots-Tag: noindex",
    "/favicon.ico",
    "  Cache-Control: public, max-age=86400",
    "/apple-touch-icon.png",
    "  Cache-Control: public, max-age=86400",
    "",
  ].join("\n"),
);

const v = hash.digest("hex").slice(0, 10);
writeFileSync(
  join(root, "worker", "src", "generated-web.ts"),
  `// GENERATED by scripts/build-web.mjs. Do not edit.\nexport const WEB_ASSETS_VERSION = "${v}";\n`,
);
console.log(`web assets ${bytes} bytes -> worker/public/s (v=${v})`);
